"""The demo catalogue: real, recognisable courses mapped onto the taxonomy.

Recognisable courses and providers, because a reviewer can judge instantly whether
recommending the Deep Learning Specialization to someone who lingered on the Machine
Learning Specialization is sensible — a judgement that is much harder to make about an
invented catalogue.

Every course declares the skills it **teaches** and the skills it **requires**, as
canonical `app.taxonomy` slugs. That is the edge the whole career layer runs on: skill
gap analysis produces a set of slugs, and `teaches` is what turns that set back into
courses someone can actually enrol in. `requires` is what stops the advisor telling a
learner to start at RAG before they can write Python.

Descriptions are written rather than templated: retrieval quality depends on them, and
a catalogue of "A good course" embeds into mush.

`learners` and `reviews` are *derived* (see `social_proof`) rather than invented per
course. Made-up numbers in fifty places drift into implausibility — one rule that keeps
a 4.9 more popular than a 4.2 stays coherent, and is honest about being a demo figure.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Course:
    title: str
    provider: str
    category: str  # taxonomy category slug
    subcategory: str  # taxonomy subcategory key, "category/sub"
    level: str  # beginner | intermediate | advanced
    price: int  # whole dollars; 0 is genuinely free
    rating: float
    hours: int
    spec: str  # the one-line syllabus shown on a card
    description: str
    teaches: tuple[str, ...]
    requires: tuple[str, ...] = ()
    objectives: tuple[str, ...] = ()
    curriculum: tuple[str, ...] = ()  # module titles, in order
    projects: tuple[str, ...] = ()
    tags: tuple[str, ...] = ()  # defaults to `teaches`; set only when it adds a term
    format: str = "Self-Paced Course"
    instructor: str = ""
    certificate: bool = True
    labs: int = 0
    assessments: int = 0
    delivery: str = "Self-Paced"
    extra: dict = field(default_factory=dict)

    @property
    def keywords(self) -> tuple[str, ...]:
        return self.tags or self.teaches


def social_proof(rating: float, price: int, hours: int) -> tuple[int, int]:
    """(learners, reviews) for a demo catalogue, derived so they stay plausible.

    Higher rated and free courses reach more people; long expensive programmes reach
    fewer. Deterministic, so re-seeding does not reshuffle the numbers under a
    screenshot.
    """
    base = 1_800 * (rating - 3.6) ** 3
    reach = 6.0 if price == 0 else max(0.4, 40.0 / (price**0.6))
    learners = int(max(400, base * reach * (1 + 40 / max(hours, 4))))
    return learners, max(30, learners // 24)


